    /** quebra o texto em células (letra + acento); caracteres que a fonte não tem são ignorados */
    fun parse(s: String): Array<Cell> {
        val hit = cache[s]
        if (hit != null) return hit
        val out = ArrayList<Cell>()
        for (ch in s.uppercase()) {
            val d = java.text.Normalizer.normalize(ch.toString(), java.text.Normalizer.Form.NFD)
            if (d.isEmpty()) continue
            val base = d[0]
            var mark = 0
            if (d.length > 1) {
                mark = when (d[1]) {
                    '\u0301' -> 1
                    '\u0300' -> 2
                    '\u0302' -> 3
                    '\u0303' -> 4
                    '\u0327' -> 5
                    '\u0308' -> 6
                    else -> 0
                }
            }
            val rows = G[base]
            if (rows != null) out.add(Cell(rows, mark))
        }
        val arr = out.toTypedArray()
        cache[s] = arr
        return arr
    }

    fun marks(m: Int): IntArray = MK[m]

    /** largura em pixels lógicos (letra 5 + 1 de espaço) */
    fun width(s: String, sc: Int): Int {
        val n = parse(s).size
        return if (n == 0) 0 else (n * 6 - 1) * sc
    }
